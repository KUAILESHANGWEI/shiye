const ShiyeI18n = (() => {
    const storageKey = 'shiye-language';
    let preference = localStorage.getItem(storageKey) || 'system';
    const dictionaries = {en: shiyeEnglish, ...shiyeAdditionalLanguages};
    const supported = ['zh', ...Object.keys(dictionaries)];
    const validPreferences = ['system', ...supported];
    if (!validPreferences.includes(preference)) preference = 'system';
    const systemLanguage = () => (navigator.languages || [navigator.language])
        .map(value => (value || '').toLowerCase().split('-')[0])
        .find(value => supported.includes(value)) || 'en';
    const language = () => preference === 'system' ? systemLanguage() : preference;
    const translate = text => language() === 'zh' ? text : (dictionaries[language()][text] ?? shiyeEnglish[text] ?? text);
    // Only register original interface nodes, before collection data is rendered.
    const textNodes = [];
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) {
        const node = walker.currentNode;
        if (node.parentElement.closest('script, style')) continue;
        const source = node.textContent.trim();
        if (Object.hasOwn(shiyeEnglish, source)) textNodes.push({node, source, original: node.textContent});
    }
    const attributes = [];
    for (const node of document.querySelectorAll('[title], [placeholder], [aria-label], [aria-placeholder]')) {
        for (const name of ['title', 'placeholder', 'aria-label', 'aria-placeholder']) {
            const source = node.getAttribute(name);
            if (source && Object.hasOwn(shiyeEnglish, source)) attributes.push({node, name, source});
        }
    }
    const title = document.title;
    function apply() {
        document.documentElement.lang = language() === 'zh' ? 'zh-CN' : language();
        document.title = translate(title);
        for (const {node, source, original} of textNodes) {
            if (node.isConnected) node.textContent = original.replace(source, translate(source));
        }
        for (const {node, name, source} of attributes) {
            if (node.isConnected) node.setAttribute(name, translate(source));
        }
        window.webkit?.messageHandlers?.setLanguage?.postMessage(preference);
    }
    apply();
    window.addEventListener('languagechange', () => {
        if (preference === 'system') {
            apply();
            window.dispatchEvent(new Event('shiye-language-changed'));
        }
    });
    return {
        t: translate,
        format(text, values) {
            return translate(text).replace(/\{(\w+)\}/g, (_, key) => String(values[key] ?? ''));
        },
        preference: () => preference,
        locale: () => language() === 'zh' ? 'zh-CN' : language(),
        setLanguage(value) {
            if (!validPreferences.includes(value)) throw Error('Invalid language');
            localStorage.setItem(storageKey, value);
            preference = value;
            apply();
        }
    };
})();
